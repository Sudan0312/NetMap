"""End-to-end pipeline: discover -> classify -> topology -> risk -> snapshot.

Both the CLI and the web API call these functions, so a scan run from the
dashboard and one run from `netmap discover` produce byte-identical snapshots
apart from timestamps.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

from . import __version__
from .config import Config
from .models import Device, Finding, ScanError, ScanSnapshot, summarize_devices
from .risk.engine import RiskEngine, band_for
from .topology.builder import build_topology
from .util import atomic_write, now_utc

Progress = Callable[[str, float, str], None]


@dataclass
class RunResult:
    snapshot: ScanSnapshot
    timings: dict[str, float] = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)

    @property
    def findings(self) -> list[Finding]:
        return self.snapshot.findings

    @property
    def risk(self) -> dict:
        return self.snapshot.risk or {}

    def to_dict(self) -> dict:
        return {"timings": self.timings, "problems": self.problems, "summary": self.snapshot.summary}


# ---------------------------------------------------------------------- discovery
def discover(cfg: Config, *, progress: Progress | None = None) -> ScanSnapshot:
    """Produce a device list according to `scan.mode` (live | lab | import)."""
    mode = str(cfg.get("scan.mode", "live")).lower()
    say = progress or (lambda *a: None)

    if mode == "lab":
        say("lab", 0.1, "building simulated network")
        from .discovery.simulator import build_devices

        devices, zones = build_devices(
            str(cfg.get("lab.size", "medium")),
            seed=int(cfg.get("lab.seed", 7)),
            include_risks=bool(cfg.get("lab.include_risks", True)),
        )
        from .discovery.engine import classify_devices, snapshot_from_devices

        classify_devices(devices)
        say("lab", 0.6, f"{len(devices)} devices")
        snap = snapshot_from_devices(devices, cfg, mode="lab", zones=zones)
        snap.notes.append("lab mode: devices are synthetic, generated by netmap.discovery.simulator")
        return snap

    if mode == "import":
        path = cfg.get("scan.import_path") or cfg.get("scan.nmap_xml")
        if not path:
            raise ValueError("scan.mode=import requires scan.import_path")
        say("import", 0.2, str(path))
        snap = load_snapshot(path)
        snap.mode = "import"
        from .discovery.engine import classify_devices

        classify_devices(snap.devices)
        return snap

    from .discovery.engine import DiscoveryEngine

    engine = DiscoveryEngine(cfg, progress=progress)
    return engine.run()


# ---------------------------------------------------------------------- analysis
def _rule_paths(cfg: Config, extra: list[str] | None) -> list[str]:
    """Resolve risk-catalogue paths: built-in first, then config files, then any
    CLI `--rules` extras on top (later files override rules by id)."""
    from .risk.engine import DEFAULT_RULES

    paths: list[str] = [DEFAULT_RULES]
    single = cfg.get("risk.rules_file")
    if single:
        paths.append(str(single))
    paths.extend(str(x) for x in (cfg.get("risk.rules_files") or []))
    paths.extend(str(x) for x in (extra or []))
    return paths


def analyze(cfg: Config, snap: ScanSnapshot, *, rules: list[str] | None = None) -> ScanSnapshot:
    """Attach topology, risk findings and scores to a snapshot (in place)."""
    t0 = time.time()
    # Zone trust has to reach the device before topology/risk run: layout tiers,
    # trust-crossing rules and SPOF annotation all read dev.trust, and imported or
    # simulated snapshots often carry only the zone name.
    zone_trust = {z.name: z.trust for z in snap.zones}
    for dev in snap.devices:
        if not dev.trust and dev.zone in zone_trust:
            dev.trust = zone_trust[dev.zone]
    metrics = build_topology(snap, cfg.get)
    snap.config["topology_metrics"] = metrics
    t_topo = time.time() - t0

    t1 = time.time()
    engine = RiskEngine(
        rules_files=_rule_paths(cfg, rules),
        config={
            "disabled": cfg.get("risk.disabled") or [],
            "only": cfg.get("risk.only") or [],
            "min_severity": cfg.get("risk.min_severity") or "info",
            "severity_overrides": cfg.get("risk.severity_overrides") or {},
            "max_findings_per_rule": int(cfg.get("risk.max_findings_per_rule") or 0),
        },
        thresholds=cfg.get("risk.thresholds") or {},
        exceptions=cfg.get("risk.exceptions") or [],
        policy={"zones": cfg.get("zones") or [], "mode": snap.mode},
    )
    engine.analyze(snap)
    t_risk = time.time() - t1

    open_findings = [f for f in snap.findings if f.status == "open"]
    summary = dict(snap.summary or {})
    summary.update(
        {
            "topology": {k: v for k, v in metrics.items() if k not in ("derived_from", "notes")},
            "risk_band": band_for(float((snap.risk or {}).get("score") or 0)),
            "open_findings": len(open_findings),
            "accepted_risk": len(snap.findings) - len(open_findings),
            "scan_errors": len(snap.errors),
            "mode": snap.mode,
        }
    )
    snap.summary = summary
    snap.counters = {
        **(snap.counters or {}),
        "links_built": len(snap.links),
        "bridges": int(metrics.get("bridges") or 0),
        "articulation_points": int(metrics.get("articulation_points") or 0),
        "findings": len(snap.findings),
    }
    snap.config["timings"] = {**(snap.config.get("timings") or {}), "topology_seconds": round(t_topo, 3), "risk_seconds": round(t_risk, 3)}
    return snap


def run(cfg: Config, *, rules: list[str] | None = None, progress: Progress | None = None) -> RunResult:
    """discover + analyze, with timings and non-fatal problems surfaced."""
    say = progress or (lambda *a: None)
    t0 = time.time()
    say("discover", 0.0, "starting")
    snap = discover(cfg, progress=progress)
    t_disc = time.time() - t0
    say("analyze", 0.8, "topology + risk")
    analyze(cfg, snap, rules=rules)
    t_all = time.time() - t0
    snap.finished = now_utc().strftime("%Y-%m-%dT%H:%M:%SZ")
    snap.duration_seconds = round(t_all, 2)
    snap.config["timings"] = {**(snap.config.get("timings") or {}), "discover_seconds": round(t_disc, 2), "total_seconds": round(t_all, 2)}
    problems = [f"{e.stage}: {e.message}" for e in snap.errors]
    say("done", 1.0, f"{len(snap.devices)} devices, {len(snap.findings)} findings")
    return RunResult(
        snapshot=snap,
        timings={"discover": round(t_disc, 2), "total": round(t_all, 2)},
        problems=problems,
    )


# ---------------------------------------------------------------------- persistence
def save_snapshot(snap: ScanSnapshot, path: str | Path) -> Path:
    path = Path(path)
    atomic_write(path, json.dumps(snap.to_dict(), indent=2, sort_keys=True, default=str) + "\n")
    return path


def load_snapshot(path: str | Path) -> ScanSnapshot:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if isinstance(data, dict) and "devices" not in data and "scan" in data:  # nmap-ish wrapper
        raise ValueError("not a NetMap snapshot; use netmap import for scanner output")
    if isinstance(data, dict) and "schema_version" not in data:
        raise ValueError(f"{path} is not a NetMap snapshot (no schema_version)")
    snap = ScanSnapshot.from_dict(data)
    err = snap.validate()
    if err:
        snap.errors.append(ScanError(stage="load", message="; ".join(err)))
    return snap


# ---------------------------------------------------------------------- comparison
def compare_snapshots(old: ScanSnapshot, new: ScanSnapshot) -> dict:
    """Diff two snapshots for change review / drift reporting."""
    o = {d.id: d for d in old.devices}
    n = {d.id: d for d in new.devices}

    def sig(dev: Device) -> dict:
        return {
            "hostname": dev.hostname,
            "os": f"{dev.os_family or ''} {dev.os_version or ''}".strip() or None,
            "zone": dev.zone,
            "type": dev.device_type,
            "criticality": dev.criticality,
            "open_ports": sorted({(s.port, s.protocol) for s in dev.services if s.is_open}),
            "risk": round(float(dev.risk_score or 0), 1),
        }

    added = sorted(set(n) - set(o))
    removed = sorted(set(o) - set(n))
    changed: list[dict] = []
    for ident in sorted(set(o) & set(n)):
        before, after = sig(o[ident]), sig(n[ident])
        delta = {k: {"was": before[k], "now": after[k]} for k in before if before[k] != after[k]}
        if delta:
            changed.append({"id": ident, "ip": n[ident].ip or o[ident].ip, "changes": delta})

    of = {f.rule_id + "|" + (f.target_id or ""): f for f in old.findings}
    nf = {f.rule_id + "|" + (f.target_id or ""): f for f in new.findings}
    resolved = [
        {"rule_id": key.split("|")[0], "title": of[key].rule_title, "target": of[key].target_label, "severity": of[key].severity}
        for key in sorted(set(of) - set(nf))
        if key in of
    ]
    appeared = [
        {"rule_id": key.split("|")[0], "title": nf[key].rule_title, "target": nf[key].target_label, "severity": nf[key].severity}
        for key in sorted(set(nf) - set(of))
        if key in nf
    ]
    score_delta = round(float(new.risk.get("score") or 0) - float(old.risk.get("score") or 0), 1)
    return {
        "old_snapshot": old.snapshot_id,
        "new_snapshot": new.snapshot_id,
        "old_finished": old.finished,
        "new_finished": new.finished,
        "devices_added": [n[i].ip or i for i in added],
        "devices_removed": [o[i].ip or i for i in removed],
        "device_changes": changed,
        "findings_appeared": appeared,
        "findings_resolved": resolved,
        "new_critical": sum(1 for x in appeared if x["severity"] == "critical"),
        "risk_score": {"was": old.risk.get("score"), "now": new.risk.get("score"), "delta": score_delta},
        "band": {"was": band_for(float(old.risk.get("score") or 0)), "now": band_for(float(new.risk.get("score") or 0))},
    }


def baseline_path(cfg: Config) -> Path | None:
    raw = cfg.get("report.baseline") or cfg.get("risk.baseline")
    return Path(str(raw)) if raw else None


def compare_with_baseline(cfg: Config, snap: ScanSnapshot) -> dict | None:
    path = baseline_path(cfg)
    if not path or not path.exists():
        return None
    return compare_snapshots(load_snapshot(path), snap)


