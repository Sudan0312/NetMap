"""Report writers: json, markdown, csv, html, sarif, cef, dot.

Every writer takes an analysed `ScanSnapshot` and returns file paths, so a CI
job can emit exactly the formats its consumers want (`json+sarif` for a merge
request, `html` for a review, `cef` for the SIEM forwarder) from one run.
"""

from __future__ import annotations

import csv
import io
import json
from pathlib import Path
from typing import Any

from .. import __version__
from ..models import Finding, ScanSnapshot
from ..util import SEVERITY_ORDER, slug

FORMATS = ("json", "md", "csv", "html", "sarif", "cef", "dot", "txt")
CEF_SEVERITY = {"critical": 10, "high": 8, "medium": 5, "low": 3, "info": 1}


def _sev_rank(sev: str) -> int:
    try:
        return SEVERITY_ORDER.index(sev)
    except ValueError:
        return 99


def _redact(value: str | None, *, macs: bool = True) -> str:
    """Mask identifiers that have no business being in a shared document."""
    text = "" if value is None else str(value)
    if not macs:
        return text
    out: list[str] = []
    for tok in text.replace("\n", " ").split(" "):
        stripped = tok.strip("(),;")
        if len(stripped) == 17 and stripped.count(":") == 5 and all(c in "0123456789abcdefABCDEF:" for c in stripped):
            out.append(tok.replace(stripped, stripped[:5] + ":**:**:**" + stripped[-3:]))
        else:
            out.append(tok)
    return " ".join(out)


def _evidence_text(finding: Finding, limit: int = 3) -> str:
    return " ; ".join(str(ev.get("text") or "") for ev in finding.evidence[:limit])


def _refs(finding: Finding) -> str:
    return " ".join(f"{k}={v}" for k, v in (finding.refs or {}).items() if k != "family")


# ---------------------------------------------------------------------- builders
def to_json(snapshot: ScanSnapshot) -> str:
    return json.dumps(snapshot.to_dict(), indent=2, sort_keys=True, default=str) + "\n"


def to_markdown(snapshot: ScanSnapshot, *, redact: bool = True, top_n: int = 25) -> str:
    risk = snapshot.risk or {}
    summary = snapshot.summary or {}
    metrics = (snapshot.config or {}).get("topology_metrics") or {}
    findings = sorted(snapshot.findings, key=lambda f: (_sev_rank(f.severity), -f.score, f.target_label))
    open_f = [f for f in findings if f.status == "open"]
    counts = {sev: sum(1 for f in open_f if f.severity == sev) for sev in SEVERITY_ORDER}
    devices = snapshot.devices
    lines: list[str] = []
    A = lines.append

    A(f"# {summary.get('title') or 'Enterprise Network Topology & Risk Report'}")
    A("")
    A(f"*Generated by NetMap {__version__} — snapshot `{snapshot.snapshot_id}`*")
    A("")
    A("| | |")
    A("|---|---|")
    A(f"| Mode | {snapshot.mode} |")
    A(f"| Operator | {snapshot.operator or '—'} |")
    A(f"| Window | {snapshot.started or '?'} → {snapshot.finished or '?'} ({snapshot.duration_seconds if snapshot.duration_seconds is not None else '?'}s) |")
    A(f"| Devices mapped | {len(devices)} ({summary.get('devices', {}).get('reachable', 0)} reachable) |")
    A(f"| Links mapped | {len(snapshot.links)} |")
    A(f"| Risk score | **{risk.get('score', 0)}/10 — {risk.get('band', 'unknown')}** |")
    A(f"| Findings | {len(open_f)} open ({', '.join(f'{counts[s]} {s}' for s in ('critical', 'high', 'medium', 'low') if counts[s])}) |")
    if snapshot.targets:
        A(f"| Targets | {len(snapshot.targets)} addresses |")
    A("")

    A("## 1. Executive summary")
    A("")
    A(_exec_summary(snapshot, open_f, counts, metrics))
    A("")

    A("## 2. Highest-impact findings")
    A("")
    if not open_f:
        A("No open findings matched the rule catalogue.")
    else:
        A("| Sev | Rule | Target | Finding | Evidence | Fix |")
        A("|---|---|---|---|---|---|")
        for f in open_f[:top_n]:
            A(
                f"| {f.severity} | `{f.rule_id}` | {_cell(f.target_label)} | {_cell(f.rule_title)} "
                f"| {_cell(_redact(_evidence_text(f)) if redact else _evidence_text(f))} | {_cell(f.remediation)} |"
            )
        if len(open_f) > top_n:
            A("")
            A(f"*{len(open_f) - top_n} further findings are listed in the CSV/JSON output.*")
    A("")

    A("## 3. Risk composition")
    A("")
    comp = risk.get("components") or {}
    A("| Component | Value |")
    A("|---|---:|")
    for key, val in comp.items():
        A(f"| {key.replace('_', ' ')} | {val} |")
    A("")
    fam = risk.get("families") or {}
    if fam:
        A("| Family | Findings | Weighted score | Worst |")
        A("|---|---:|---:|---|")
        for name, meta in fam.items():
            A(f"| {name} | {meta.get('count')} | {meta.get('score')} | {meta.get('worst')} |")
        A("")

    A("## 4. Topology and resilience")
    A("")
    A("| Metric | Value |")
    A("|---|---:|")
    for key in ("nodes", "links", "components", "bridges", "articulation_points", "isolated_nodes", "link_coverage_pct", "spof_links", "redundant_links", "trust_crossings"):
        if key in metrics:
            A(f"| {key.replace('_', ' ')} | {metrics[key]} |")
    derived = metrics.get("derived_from") or {}
    if derived:
        A("")
        A("Links by evidence source: " + ", ".join(f"{k} = {v}" for k, v in derived.items()) + ".")
    if metrics.get("notes"):
        A("")
        for note in metrics["notes"][:6]:
            A(f"> {note}")
    A("")

    A("## 5. Zones")
    A("")
    A("| Zone | Trust | Devices | CIDRs | VLANs | Segmentation |")
    A("|---|---|---:|---|---|---|")
    for z in snapshot.zones:
        seg = "enforced" if z.segmentation_enforced else (f"**not enforced** — {z.segmentation_note}" if z.segmentation_note else "not enforced")
        A(f"| {z.name} | {z.trust} | {z.device_count or len(snapshot.devices_by(zone=z.name))} | {', '.join(z.cidrs) or '—'} | {', '.join(str(v) for v in z.vlans) or '—'} | {seg} |")
    A("")

    A("## 6. Devices at risk")
    A("")
    A("| Host | Address | Type | OS / version | Zone | Ports | Crit | Risk | Findings |")
    A("|---|---|---|---|---|---:|---:|---:|---:|")
    by_target: dict[str, int] = {}
    for f in findings:
        by_target[f.target_id] = by_target.get(f.target_id, 0) + 1
    for d in sorted(devices, key=lambda x: (-(x.risk_score or 0), x.label))[: max(10, top_n)]:
        osbits = " ".join(str(x) for x in (d.os_family, d.os_version) if x) or "—"
        addr = _redact(f"{d.ip or '—'} {d.mac or ''}".strip()) if redact else f"{d.ip or '—'} {d.mac or ''}".strip()
        A(
            f"| {d.hostname or '—'} | {addr} | {d.device_type} | {osbits} | {d.zone or '—'} "
            f"| {len(d.open_ports)} | {d.criticality} | {d.risk_score:.1f} | {by_target.get(d.id, 0)} |"
        )
    A("")

    A("## 7. Everything else open")
    A("")
    A("| Sev | Rule | Target | Finding |")
    A("|---|---|---|---|")
    for f in open_f[top_n:]:
        A(f"| {f.severity} | `{f.rule_id}` | {_cell(f.target_label)} | {_cell(f.rule_title)} |")
    A("")

    A("## 8. Method, coverage and caveats")
    A("")
    A(_method_section(snapshot))
    A("")

    if snapshot.drift:
        A("## 9. Change since baseline")
        A("")
        A(_drift_markdown(snapshot.drift))
        A("")
    return "\n".join(lines)


def _cell(text: Any) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def _exec_summary(snapshot: ScanSnapshot, open_f: list[Finding], counts: dict, metrics: dict) -> str:
    devices = snapshot.devices
    risk = snapshot.risk or {}
    crit = [f for f in open_f if f.severity == "critical"]
    undocumented = [d for d in devices if not d.documented]
    plaintext = [f for f in open_f if f.rule_id.startswith("NM-PLN") or f.rule_id.startswith("NM-SNMP")]
    eol = [f for f in open_f if f.rule_id.startswith("NM-LC")]
    bits: list[str] = []
    bits.append(
        f"{len(devices)} devices and {len(snapshot.links)} links were mapped. "
        f"The network scores **{risk.get('score', 0)}/10 ({risk.get('band', 'unknown')})**."
    )
    if crit:
        where: dict[str, int] = {}
        for f in crit:
            where[f.zone or "unassigned"] = where.get(f.zone or "unassigned", 0) + 1
        bits.append(
            f"{len(crit)} critical findings concentrate in " + ", ".join(f"{k} ({v})" for k, v in sorted(where.items(), key=lambda kv: -kv[1])[:4]) + "."
        )
    if plaintext:
        bits.append(f"{len(plaintext)} findings are management-plane exposure: cleartext protocols or guessable SNMP strings.")
    if eol:
        bits.append(f"{len(eol)} lifecycle findings (end-of-life or stale firmware) are present.")
    if undocumented:
        bits.append(f"{len(undocumented)} responding devices are absent from the inventory of record.")
    bridges = int(metrics.get("bridges") or 0)
    if bridges:
        bits.append(f"{bridges} links are single points of failure; removing one splits the map.")
    coverage = metrics.get("link_coverage_pct")
    if coverage is not None:
        bits.append(f"Layer-2/3 correlation resolved adjacency for {coverage}% of mapped devices.")
    bits.append(
        "Start with anything that is both internet-reachable and running end-of-life software, "
        "then remove default credentials from the management plane, then fix the single-homed floors."
    )
    return "\n\n".join("> " + b for b in bits)


def _method_section(snapshot: ScanSnapshot) -> str:
    cfg = snapshot.config or {}
    audit = cfg.get("risk_audit") or {}
    stages = cfg.get("stages") or []
    lines = [
        f"- Discovery mode `{snapshot.mode}`; stage pipeline: " + (", ".join(f"{s.get('name')} ({s.get('seconds')}s)" for s in stages) if isinstance(stages, list) and stages and isinstance(stages[0], dict) else "simulated/lab generator"),
        f"- Rule catalogue: {audit.get('rules_active', '?')} of {audit.get('rules_total', '?')} rules active; "
        f"{len(audit.get('skipped') or {})} disabled by configuration.",
        "- Services are classified from banner + port heuristics; encryption state comes from a real TLS handshake where the port answered.",
        "- Identity/lifecycle data comes from SNMP sysDescr/sysObjectID plus a built-in vendor EOL table, matched by product and version family.",
        "- Adjacency comes from LLDP/CDP neighbour tables, shared ARP/FDB rows and routing next-hops, in that order of trust.",
        "- **Not covered:** devices that never respond, encrypted payloads (no credential verification was attempted), "
        "configurations that require SSH/API access, and any device outside the scanned ranges.",
        "- Findings are advisory. Confirm on the device before changing production configuration.",
    ]
    if snapshot.errors:
        lines.append(f"- {len(snapshot.errors)} scan-stage errors were recorded; see the errors array in the JSON output.")
    if audit.get("errors"):
        lines.append("- Rule evaluation problems: " + "; ".join(str(x) for x in audit["errors"][:5]))
    return "\n".join(lines)


def _drift_markdown(drift: dict) -> str:
    rows = [
        f"- Snapshot pair: `{drift.get('old_snapshot')}` → `{drift.get('new_snapshot')}`",
        f"- Risk score {drift.get('risk_score', {}).get('was')} → {drift.get('risk_score', {}).get('now')} "
        f"(Δ {drift.get('risk_score', {}).get('delta')}), band {drift.get('band', {}).get('was')} → {drift.get('band', {}).get('now')}",
        f"- Devices: {len(drift.get('devices_added') or [])} new, {len(drift.get('devices_removed') or [])} gone",
        f"- Findings: {len(drift.get('findings_appeared') or [])} appeared, {len(drift.get('findings_resolved') or [])} resolved "
        f"({drift.get('new_critical', 0)} of the new ones critical)",
    ]
    for key in ("devices_added", "devices_removed"):
        items = drift.get(key) or []
        if items:
            rows.append(f"- {key.replace('_', ' ')}: " + ", ".join(str(x) for x in items[:20]))
    for item in (drift.get("findings_appeared") or [])[:10]:
        rows.append(f"- NEW `{item.get('rule_id')}` [{item.get('severity')}] on {item.get('target')}")
    for item in (drift.get("findings_resolved") or [])[:10]:
        rows.append(f"- fixed `{item.get('rule_id')}` on {item.get('target')}")
    return "\n".join(rows)


def to_txt(snapshot: ScanSnapshot) -> str:
    """Short console-friendly digest (used by `netmap ci`)."""
    risk = snapshot.risk or {}
    open_f = [f for f in snapshot.findings if f.status == "open"]
    lines = [
        f"NetMap {risk.get('score', 0)}/10 ({risk.get('band', 'unknown')}) — {len(snapshot.devices)} devices, "
        f"{len(snapshot.links)} links, {len(open_f)} open findings",
    ]
    for f in sorted(open_f, key=lambda x: x.sort_key)[:15]:
        lines.append(f"  [{f.severity:>8}] {f.rule_id:<12} {f.target_label[:34]:<34} {f.rule_title}")
    return "\n".join(lines) + "\n"


def to_csv_rows(snapshot: ScanSnapshot) -> dict[str, list[dict[str, Any]]]:
    findings = [
        {
            "rule_id": f.rule_id,
            "rule_version": f.rule_version,
            "severity": f.severity,
            "score": round(f.score, 2),
            "confidence": f.confidence,
            "status": f.status,
            "scope": f.scope,
            "target_id": f.target_id,
            "target": f.target_label,
            "zone": f.zone or "",
            "device_type": f.device_type or "",
            "criticality": f.criticality,
            "exposed_to_wan": f.exposed,
            "title": f.rule_title,
            "description": f.description,
            "evidence": _evidence_text(f, 5),
            "remediation": f.remediation,
            "refs": _refs(f),
            "first_seen": f.first_seen,
            "fingerprint": f.fingerprint,
        }
        for f in sorted(snapshot.findings, key=lambda x: (x.sort_key, x.target_label))
    ]
    devices = []
    for d in snapshot.devices:
        devices.append(
            {
                "id": d.id,
                "ip": d.ip or "",
                "hostname": d.hostname or "",
                "mac": d.mac or "",
                "type": d.device_type,
                "role": d.role or "",
                "vendor": d.vendor or "",
                "model": d.model or "",
                "os_family": d.os_family or "",
                "os_version": d.os_version or "",
                "firmware": d.firmware or "",
                "os_eol": d.os_eol or "",
                "zone": d.zone or "",
                "trust": d.trust or "",
                "vlan": d.vlan or "",
                "criticality": d.criticality,
                "documented": d.documented,
                "exposed_to_wan": d.exposed_to_wan,
                "reachable": d.reachable,
                "open_ports": " ".join(str(p) for p in sorted(d.open_ports)),
                "open_port_count": len(d.open_ports),
                "plaintext_services": " ".join(sorted({s.name or str(s.port) for s in d.services if s.is_plaintext and s.is_open})),
                "links": len({l.id for l in snapshot.links if d.id in (l.src_device, l.dst_device)}),
                "risk_score": round(d.risk_score, 2),
                "discovery_sources": " ".join(d.discovery_sources),
                "uptime_seconds": d.uptime_seconds or "",
                "last_seen": d.last_seen or "",
            }
        )
    links = []
    for l in snapshot.links:
        links.append(
            {
                "id": l.id,
                "src": l.src_device,
                "src_interface": l.src_interface or "",
                "dst": l.dst_device,
                "dst_interface": l.dst_interface or "",
                "kind": l.kind,
                "speed_mbps": l.speed_mbps or "",
                "confidence": l.confidence,
                "derived_from": " ".join(l.derived_from),
                "protected": l.protected,
                "is_spof": l.is_spof,
                "redundant_group": l.redundant_group or "",
                "risk_score": round(float(l.risk_score or 0), 2),
                "carries": " ".join(l.carries),
            }
        )
    services = []
    for d in snapshot.devices:
        for s in d.services:
            services.append(
                {
                    "device_id": d.id,
                    "ip": d.ip or "",
                    "hostname": d.hostname or "",
                    "port": s.port,
                    "protocol": s.protocol,
                    "state": s.state,
                    "name": s.name or "",
                    "product": s.product or "",
                    "version": s.version or "",
                    "encryption": s.encryption or "",
                    "plaintext": s.is_plaintext,
                    "certificate": (s.certificate.subject_cn or "") if s.certificate else "",
                    "cert_not_after": (s.certificate.not_after or "") if s.certificate else "",
                    "tls_protocol": (s.certificate.protocol or "") if s.certificate else "",
                    "confidence": s.confidence,
                    "banner": (s.banner or "").replace("\r", " ").replace("\n", " ")[:240],
                }
            )
    zones = [
        {
            "zone": z.name,
            "trust": z.trust,
            "devices": z.device_count or len(snapshot.devices_by(zone=z.name)),
            "cidrs": " ".join(z.cidrs),
            "vlans": " ".join(str(v) for v in z.vlans),
            "default_gateway": z.default_gateway or "",
            "segmentation_enforced": z.segmentation_enforced,
            "note": z.segmentation_note or "",
        }
        for z in snapshot.zones
    ]
    return {"findings": findings, "devices": devices, "links": links, "services": services, "zones": zones}


def to_csv(snapshot: ScanSnapshot) -> dict[str, str]:
    """Return one CSV string per table (writer decides file names)."""
    out: dict[str, str] = {}
    for name, rows in to_csv_rows(snapshot).items():
        buf = io.StringIO()
        if not rows:
            out[name] = ""
            continue
        writer = csv.DictWriter(buf, fieldnames=list(rows[0].keys()), lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: ("" if v is None else v) for k, v in row.items()})
        out[name] = buf.getvalue()
    return out


def to_sarif(snapshot: ScanSnapshot, rules: list | None = None) -> str:
    """SARIF 2.1.0 so the findings land in GitHub code scanning / SARIF viewers."""
    catalogue = {r.id: r for r in (rules or [])}
    seen_rules: dict[str, dict] = {}
    results = []
    for f in snapshot.findings:
        rule = catalogue.get(f.rule_id)
        if f.rule_id not in seen_rules:
            seen_rules[f.rule_id] = {
                "id": f.rule_id,
                "name": _sify(f.rule_id),
                "shortDescription": {"text": f.rule_title},
                "fullDescription": {"text": f.description or f.rule_title},
                "helpUri": (f.refs or {}).get("url") or "https://example.invalid/netmap/rules",
                "properties": {
                    "tags": sorted({str(k) + ":" + str(v) for k, v in (f.refs or {}).items() if k != "family"}),
                    "security-severity": str(min(10.0, max(0.1, float(f.impact or 5) * 1.0))),
                    "rule-version": f.rule_version,
                },
                "defaultConfiguration": {"level": _sarif_level(rule.severity if rule else f.severity)},
            }
        region = None
        results.append(
            {
                "ruleId": f.rule_id,
                "ruleIndex": list(seen_rules).index(f.rule_id),
                "level": _sarif_level(f.severity),
                "message": {"text": _message(f)},
                "suppression": ({"kind": "external", "justification": f.status_note or f.status} if f.status != "open" else None),
                "locations": [
                    {
                        "physicalLocation": {
                            "artifactLocation": {"uri": f"network://{slug(f.target_label or f.target_id)}", "uriBaseId": "%SRCROOT%"},
                            **({"region": region} if region else {}),
                        },
                        "logicalLocations": [{"fullyQualifiedName": f.target_id, "kind": "network-device"}],
                    }
                ],
                "partialFingerprints": {"netmap/1": f.fingerprint},
                "properties": {
                    "netmap:target": f.target_label,
                    "netmap:score": f.score,
                    "netmap:confidence": f.confidence,
                    "netmap:zone": f.zone,
                    "netmap:remediation": f.remediation,
                },
            }
        )
    payload = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "NetMap",
                        "version": __version__,
                        "informationUri": "https://example.invalid/netmap",
                        "rules": list(seen_rules.values()),
                    }
                },
                "automationDetails": {"id": f"netmap/{snapshot.snapshot_id}"},
                "columnKind": "utf16Codes",
                "results": results,
                "invocations": [
                    {
                        "executionSuccessful": True,
                        "startTimeUtc": snapshot.started,
                        "endTimeUtc": snapshot.finished,
                        "properties": {
                            "mode": snapshot.mode,
                            "devices": len(snapshot.devices),
                            "links": len(snapshot.links),
                            "riskScore": (snapshot.risk or {}).get("score"),
                            "riskBand": (snapshot.risk or {}).get("band"),
                        },
                    }
                ],
            }
        ],
    }
    if snapshot.errors:
        payload["runs"][0]["invocations"][0]["toolExecutionNotifications"] = [
            {"level": "warning", "message": {"text": f"{e.stage}: {e.message}"}} for e in snapshot.errors[:50]
        ]
    return json.dumps(payload, indent=2, sort_keys=True, default=str) + "\n"


def _sify(rule_id: str) -> str:
    return "netmap-" + rule_id.lower().replace("_", "-")


def _sarif_level(sev: str) -> str:
    return {"critical": "error", "high": "error", "medium": "warning", "low": "note"}.get(sev, "none")


def _message(f: Finding) -> str:
    head = f"{f.rule_title} on {f.target_label}."
    ev = _evidence_text(f)
    fix = f"Fix: {f.remediation}" if f.remediation else ""
    return " ".join(x for x in (head, ev, fix) if x).strip()


def to_cef(snapshot: ScanSnapshot, *, device_vendor_product: str = "NetMap") -> str:
    """ArcSight CEF lines for SIEM ingest (one per open finding)."""
    lines: list[str] = []
    for f in snapshot.findings:
        if f.status != "open":
            continue
        ext = {
            "rt": (snapshot.finished or "").replace(" ", "T"),
            "msg": f.rule_title,
            "deviceReceiptTime": (snapshot.finished or "").replace(" ", "T"),
            "cs1Label": "rule",
            "cs1": f.rule_id,
            "cs2Label": "zone",
            "cs2": f.zone or "unassigned",
            "cs3Label": "score",
            "cs3": f"{f.score:.1f}",
            "externalId": f.fingerprint[:24],
        }
        ip = ""
        for tok in (f.target_label or "").replace(")", " ").split():
            if tok and tok[0].isdigit() and tok.count(".") == 3:
                ip = tok
                break
        if ip:
            ext["src"] = ip
        evidence = _evidence_text(f)
        if evidence:
            ext["sproc"] = evidence[:240]
        if f.device_type:
            ext["deviceProcessName"] = f.device_type
        head = f"CEF:0|{device_vendor_product}|netmap|{__version__}|{f.rule_id}|{_esc_cef(f.rule_title)}|{CEF_SEVERITY.get(f.severity, 5)}|"
        lines.append(head + " ".join(f"{k}={_esc_cef(v)}" for k, v in ext.items()))
    return "\n".join(lines) + ("\n" if lines else "")


def _esc_cef(value: Any) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ").replace("\r", " ").replace("=", "\\=")


def to_dot(snapshot: ScanSnapshot) -> str:
    """Graphviz source for people who keep topology in a repo."""
    lines = ["digraph netmap {", "  rankdir=TB;", "  node [shape=box, style=\"rounded,filled\", fontname=\"Helvetica\"];"]
    by_id = snapshot.device_map()
    for d in snapshot.devices:
        colour = {0: "#ffffff", 1: "#e2e3e5", 2: "#fef3c7", 3: "#fed7aa", 4: "#fca5a5", 5: "#b3261e"}.get(
            5 if (d.risk_score or 0) >= 9 else 4 if (d.risk_score or 0) >= 7 else 3 if (d.risk_score or 0) >= 4.5 else 2 if (d.risk_score or 0) >= 2 else 1, "#ffffff"
        )
        label = _esc_dot(f"{d.hostname or d.ip or d.id}\\n{d.device_type} · {d.zone or '—'}")
        lines.append(f'  "{_esc_dot(d.id)}" [label="{label}", fillcolor="{colour}"];')
    for l in snapshot.links:
        style = ' [style="dashed", color="#c2410c"]' if l.is_spof else (' [color="#0f766e"]' if l.protected else "")
        lines.append(f'  "{_esc_dot(l.src_device)}" -> "{_esc_dot(l.dst_device)}"{style};')
    for z in snapshot.zones:
        members = [d for d in snapshot.devices if d.zone == z.name]
        if not members:
            continue
        zlabel = _esc_dot(z.name + " [" + z.trust + "]")
        zline = '  subgraph cluster_{0} {{ label="{1}"; style=rounded; color="#94a3b8";'.format(slug(z.name), zlabel)
        lines.append(zline)
        for d in members:
            lines.append(f'    "{_esc_dot(d.id)}";')
        lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _esc_dot(text: str) -> str:
    return str(text).replace('"', "'")


# ---------------------------------------------------------------------- entry point
def write_report(
    snapshot: ScanSnapshot,
    out_dir: str | Path,
    *,
    formats: list[str] | None = None,
    title: str | None = None,
    redact: bool = True,
    rules: list | None = None,
    base_name: str | None = None,
) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    formats = [f.lower().strip() for f in (formats or ["json", "md"]) if f and f.lower().strip() in FORMATS]
    stamp = (snapshot.finished or snapshot.started or "").replace(":", "").replace("-", "").replace("T", "-")[:15] or "report"
    stem = base_name or f"netmap-{slug(snapshot.mode)}-{stamp or 'report'}"
    written: dict[str, Path] = {}

    for fmt in formats:
        path = out / f"{stem}.{ 'md' if fmt == 'md' else fmt}"
        if fmt == "json":
            text = to_json(snapshot)
        elif fmt == "md":
            text = to_markdown(snapshot, redact=redact)
        elif fmt == "txt":
            text = to_txt(snapshot)
        elif fmt == "sarif":
            text = to_sarif(snapshot, rules=rules)
        elif fmt == "cef":
            text = to_cef(snapshot)
        elif fmt == "dot":
            text = to_dot(snapshot)
        elif fmt == "html":
            from ..viz.static_html import render_html

            text = render_html(snapshot, title=title)
        elif fmt == "csv":
            for name, body in to_csv(snapshot).items():
                csv_path = out / f"{stem}-{name}.csv"
                csv_path.write_text(body, encoding="utf-8")
                written[f"csv:{name}"] = csv_path
            continue
        else:  # pragma: no cover - FORMATS gate
            continue
        path.write_text(text, encoding="utf-8")
        written[fmt] = path
    return written


